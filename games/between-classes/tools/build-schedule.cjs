const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const data = JSON.parse(fs.readFileSync(path.join(root, 'data/schedule.json'), 'utf8'));
const output = '// Generated by tools/build-schedule.cjs; edit data/schedule.json.\nwindow.CampusSchedule = ' + JSON.stringify(data, null, 2).replace(/</g, '\\u003c') + ';\n';
const dest = path.join(root, 'data/schedule.browser.js');
if (process.argv.includes('--check')) {
  if (!fs.existsSync(dest) || fs.readFileSync(dest, 'utf8') !== output) throw new Error('Schedule bundle is stale: run node games/between-classes/tools/build-schedule.cjs');
} else fs.writeFileSync(dest, output);
